namespace Cheari.Controls.Axes;

/// <summary>
/// 轴位置枚举，定义坐标轴在图表中的位置。
/// </summary>
public enum AxisPlacement
{
    /// <summary>
    /// 左侧位置，通常用于Y轴。
    /// </summary>
    Left,

    /// <summary>
    /// 右侧位置，通常用于Y轴。
    /// </summary>
    Right,

    /// <summary>
    /// 顶部位置，通常用于X轴。
    /// </summary>
    Top,

    /// <summary>
    /// 底部位置，通常用于X轴。
    /// </summary>
    Bottom
}