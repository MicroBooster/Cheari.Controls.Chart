namespace Cheari.Controls.Core;

/// <summary>
/// 标记点类型枚举，定义散点图中数据点的标记形状。
/// </summary>
public enum MarkerType
{
    /// <summary>
    /// 圆形标记。
    /// </summary>
    Circle,

    /// <summary>
    /// 方形标记。
    /// </summary>
    Square,

    /// <summary>
    /// 菱形标记。
    /// </summary>
    Diamond,

    /// <summary>
    /// 向上三角形标记。
    /// </summary>
    TriangleUp,

    /// <summary>
    /// 向下三角形标记。
    /// </summary>
    TriangleDown
}