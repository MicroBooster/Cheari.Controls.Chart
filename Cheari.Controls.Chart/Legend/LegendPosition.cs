namespace Cheari.Controls.Legend;

/// <summary>
/// 图例位置枚举，定义图例可以放置的位置。
/// </summary>
public enum LegendPosition
{
    /// <summary>内部顶部 - 图例位于绘图区域内顶部。</summary>
    InternalTop,
    /// <summary>内部底部 - 图例位于绘图区域内底部。</summary>
    InternalBottom,
    /// <summary>内部左侧 - 图例位于绘图区域内左侧。</summary>
    InternalLeft,
    /// <summary>内部右侧 - 图例位于绘图区域内右侧。</summary>
    InternalRight,
    /// <summary>外部顶部 - 图例位于绘图区域外顶部。</summary>
    ExternalTop,
    /// <summary>外部底部 - 图例位于绘图区域外底部。</summary>
    ExternalBottom,
    /// <summary>外部左侧 - 图例位于绘图区域外左侧。</summary>
    ExternalLeft,
    /// <summary>外部右侧 - 图例位于绘图区域外右侧。</summary>
    ExternalRight
}
